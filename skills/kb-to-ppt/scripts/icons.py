def _arc(cx, cy, r, a0, a1, n=18, ry=None):
    ry = ry or r
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy - ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def _heart():
    pts = []
    for i in range(40):
        t = 2 * math.pi * i / 40
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        pts.append((12 + x * 0.62, 11.2 - y * 0.62))
    return pts


def _star(cx=12, cy=12.6, r1=10.5, r2=4.3, n=5):
    pts = []
    for i in range(n * 2):
        r = r1 if i % 2 == 0 else r2
        a = math.radians(90 + 180.0 * i / n)
        pts.append((cx + r * math.cos(a), cy - r * math.sin(a)))
    return pts


def _gear(cx=12, cy=12, r1=10.2, r2=7.6, teeth=8):
    pts = []
    for i in range(teeth * 4):
        a = math.radians(360.0 * i / (teeth * 4) + 360.0 / teeth / 8)
        r = r1 if (i % 4) in (0, 1) else r2
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


