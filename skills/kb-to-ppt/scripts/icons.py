# 关键词 → 图标（自动匹配用，按顺序优先）


def match_icon(s, default=None, used=None):
    """按 tap-config/icons.json 的关键词表给文字配图标。"""
    s = str(s or "")
    default = default or CONF.raw.get("icon_default", "star")
    for kws, name in CONF.raw.get("icon_keywords", []):
        if any(k in s for k in kws) and (not used or name not in used):
            return name
    return default


def _thick(points, w):
    """把折线转成若干四边形 + 关节圆，得到等宽粗线。"""
    out = []
    for (x1, y1), (x2, y2) in zip(points, points[1:]):
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy) or 1
        nx, ny = -dy / L * w / 2, dx / L * w / 2
        out.append(("p", [(x1 + nx, y1 + ny), (x2 + nx, y2 + ny), (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)]))
    for (x, y) in points[1:-1]:
        out.append(("c", x, y, w / 2))
    return out


def draw_icon(slide, name, x, y, size, color, cut=None):
    """在 (x, y) 英寸处画边长 size 英寸的图标，返回组合形状。未知图标名时用 star。"""
    prims = ICONS.get(name) or ICONS["star"]
    grp = slide.shapes.add_group_shape()
    shapes = grp.shapes
    k = size * 914400 / 24.0
    ox, oy = I(x), I(y)

    def fillc(sp, role):
        sp.fill.solid()
        sp.fill.fore_color.rgb = rgb(color if role == "f" else (cut or BRAND["white"]))
        sp.line.fill.background()
        sp.shadow.inherit = False

    def poly(pts, role):
        # 自由曲线的路径坐标会被取整，所以局部坐标放大 100 倍再缩放，避免 1.5 这类坐标失真
        q = [(int(round(px * 100)), int(round(py * 100))) for px, py in pts]
        fb = shapes.build_freeform(q[0][0], q[0][1], scale=k / 100.0)
        fb.add_line_segments(q[1:], close=True)
        sp = fb.convert_to_shape(ox, oy)
        fillc(sp, role)

    def oval(cx, cy, rx, ry, role):
        sp = shapes.add_shape(MSO_SHAPE.OVAL, Emu(int(ox + (cx - rx) * k)), Emu(int(oy + (cy - ry) * k)),
                              Emu(int(2 * rx * k)), Emu(int(2 * ry * k)))
        fillc(sp, role)

    for pr in prims:
        kind = pr[0]
        if kind == "p":
            poly(pr[1], pr[2])
        elif kind == "c":
            oval(pr[1], pr[2], pr[3], pr[3], pr[4])
        elif kind == "e":
            oval(pr[1], pr[2], pr[3], pr[4], pr[5])
        elif kind == "r":
            sp = shapes.add_shape(MSO_SHAPE.RECTANGLE, Emu(int(ox + pr[1] * k)), Emu(int(oy + pr[2] * k)),
                                  Emu(int(pr[3] * k)), Emu(int(pr[4] * k)))
            fillc(sp, pr[5])
        elif kind == "t":
            for sub in _thick(pr[1], pr[2]):
                if sub[0] == "p":
                    poly(sub[1], pr[3])
                else:
                    oval(sub[1], sub[2], sub[3], sub[3], pr[3])
    return grp


def icon_badge(slide, name, x, y, d, bg, fg=None, kind="oval", ratio=0.56):
    """图标徽章：底色圆（或圆角方）+ 居中图标。镂空部分用底色绘制。"""
    from ppt_base import shape
    shape(slide, "oval" if kind == "oval" else "round", x, y, d, d, fill=bg, radius=0.28 if kind != "oval" else None)
    s = d * ratio
    return draw_icon(slide, name, x + (d - s) / 2, y + (d - s) / 2, s, fg or BRAND["white"], bg)
